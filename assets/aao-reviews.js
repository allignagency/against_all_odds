  function esc(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  /* Percentage fill for one star at position `index` (1-5) given a rating. Loox snapped to
     empty / half / full; we do the same so the row reads the same at a glance. */
  function starPct(rating, index) {
    var d = rating - (index - 1);
    if (d >= 0.75) return 100;
    if (d >= 0.25) return 50;
    return 0;
  }

  function starsHTML(rating, label) {
    var out = '<span class="aao-stars" role="img" aria-label="' + esc(label || (Math.round(rating * 10) / 10) + ' out of 5 stars') + '">';
    for (var i = 1; i <= 5; i++) {
      out +=
        '<svg class="aao-star" viewBox="0 0 24 24" aria-hidden="true" focusable="false" style="--aao-star-pct:' +
        starPct(rating, i) +
        '%"><path class="aao-star__fill" fill="currentColor" d="' +
        STAR_FILL +
        '"/><path class="aao-star__line" fill="currentColor" d="' +
        STAR_LINE +
        '"/></svg>';
    }
    return out + '</span>';
  }

  function fmtDate(value) {
    if (!value) return '';
    var d = new Date(value);
    if (isNaN(d.getTime())) return String(value);
    try {
      return d.toLocaleDateString(document.documentElement.lang || 'en-GB', {
        year: 'numeric',
        month: 'long',
        day: 'numeric'
      });
    } catch (e) {
      return d.toDateString();
    }
  }

  function toTime(value) {
    var t = new Date(value).getTime();
    return isNaN(t) ? 0 : t;
  }

  /* --- data ----------------------------------------------------------------------------------
     The harvest is split across theme assets so no page downloads more than it needs, and so the
     same review set is not stored once per product that displays it:

       aao-reviews-summary.json      one row per handle - avg/count (what the product displays),
                                     own_avg/own_count (its genuine reviews), pool, and `src`:
                                     the asset holding its review list. Fetched once per page that
                                     renders a badge or the widget.
       aao-reviews-store.json        the store-wide showcase set Loox served on products with no
                                     reviews of their own.
       aao-reviews-set-<hash>.json   the other shared sets.
       aao-reviews-p-<handle>.json   products that have a review set of their own.

     A handle absent from the summary has no reviews, so nothing further is requested for it.
     docs/reviews/split_reviews.py produces all of these from the harvest file. */

  var bakedSummaryPromise = null;
  var summaryPromise = null;
  var overlayPromise = null;
  var productPromises = {};

  function readInline(id) {
    var el = document.getElementById(id);
    if (!el) return null;
    try {
      var parsed = JSON.parse(el.textContent);
      return parsed && (parsed.products || parsed.reviews) ? parsed : null;
    } catch (e) {
      return null;
    }
  }

  function fetchJSON(url) {
    if (!url) return Promise.resolve(null);
    return fetch(url, { credentials: 'omit' })
      .then(function (r) {
        return r.ok ? r.json() : null;
      })
      .catch(function () {
        return null;
      });
  }

  function loadOverlay() {
    if (overlayPromise) return overlayPromise;
    overlayPromise = cfg.approvedUrl ? fetchJSON(cfg.approvedUrl) : Promise.resolve(null);
    return overlayPromise;
  }

  function overlayEntry(overlay, handle) {
    if (!overlay || !overlay.products || !handle) return null;
    return overlay.products[handle] || null;
  }

  /* --- summary (badges) ---------------------------------------------------------------------- */

  /* The overlay carries full review objects, not summary rows, so fold its ratings into the baked
     avg/count arithmetically. The widget does the authoritative de-duplicated merge; a badge can
     be off by one only if the overlay re-publishes a review that is already baked in. */
  function foldOverlayIntoSummary(summary, overlay) {
    var products = {};
    var h;
    if (summary && summary.products) {
      for (h in summary.products) {
        if (!Object.prototype.hasOwnProperty.call(summary.products, h)) continue;
        var row = summary.products[h];
        /* In genuine-only mode a product is represented by its own reviews, so the shared
           showcase set it displays today counts for nothing. */
        products[h] = GENUINE_ONLY
          ? { avg: row.own_avg || 0, count: row.own_count || 0, src: row.src, pool: !!row.pool }
          : { avg: row.avg, count: row.count, src: row.src, pool: !!row.pool };
      }
    }
    if (overlay && overlay.products) {
      for (h in overlay.products) {
        if (!Object.prototype.hasOwnProperty.call(overlay.products, h)) continue;
        var fresh = overlay.products[h];
        var extra = fresh.reviews || [];
        var base = products[h];
        if (!base || fresh.replace === true || !base.count) {
          var n = typeof fresh.count === 'number' ? fresh.count : extra.length;
          var a =
            typeof fresh.avg === 'number'
              ? fresh.avg
              : extra.length
                ? sumRatings(extra) / extra.length
                : 0;
          if (n) {
            products[h] = {
              avg: Math.round(a * 10) / 10,
              count: n,
              src: base && base.src,
              pool: false
            };
          }
          continue;
        }
        var total = base.count + extra.length;
        if (!total) continue;
        products[h] = {
          avg: Math.round(((base.avg * base.count + sumRatings(extra)) / total) * 10) / 10,
          count: total,
          src: base.src,
          /* A moderated submission is genuine, so the product is no longer showcase-only. */
          pool: false
        };
      }
    }
    return { products: products };
  }

  function sumRatings(list) {
    return list.reduce(function (a, r) {
      return a + (Number(r.rating) || 0);
    }, 0);
  }

  /* The baked summary exactly as shipped, with no overlay folded in. Used to decide whether a
     per-product asset exists before requesting it. */
  function loadBakedSummary() {
    if (bakedSummaryPromise) return bakedSummaryPromise;
    var inline = readInline('aao-reviews-summary-data');
    bakedSummaryPromise = inline ? Promise.resolve(inline) : fetchJSON(cfg.summaryUrl);
    return bakedSummaryPromise;
  }

  function loadSummary() {
    if (summaryPromise) return summaryPromise;
    summaryPromise = Promise.all([loadBakedSummary(), loadOverlay()]).then(function (res) {
      return foldOverlayIntoSummary(res[0], res[1]);
    });
    return summaryPromise;
  }

  /* --- one product's reviews (widget) --------------------------------------------------------- */

  /* Theme asset directory, e.g. https://cdn.shopify.com/s/files/1/.../assets/ - the boot snippet
     derives it from a known asset's URL. Used for the review-list assets and the photos. */
  function assetBase() {
    if (cfg.assetBase) return cfg.assetBase;
    if (cfg.summaryUrl) return cfg.summaryUrl.split('?')[0].replace(/[^/]+$/, '');
    return '';
  }

  /* `src` in the summary names the asset holding this handle's review list: the shared showcase
     set, one of the other shared sets, or its own file. The ?v= cache buster is not reproduced -
     it is per-asset, and Shopify serves the file with or without it. */
  function reviewsAssetUrl(row, explicit) {
    if (explicit) return explicit;
    if (!row || !row.src) return null;
    return assetBase() + row.src;
  }

  /* Photos are baked as bare asset filenames so the data stays portable across stores. Anything
     that already looks like a URL or an absolute path is left alone (e.g. overlay submissions). */
  function photoUrl(value) {
    if (!value) return '';
    if (/^(https?:)?\/\//.test(value) || value.charAt(0) === '/') return value;
    return assetBase() + value;
  }

  /* Merge the overlay's approved reviews onto the baked list for one product, de-duplicating on
     author|date|text so a re-published review cannot appear twice, then recompute avg/count. */
  function mergeProduct(base, fresh) {
    if (!base && !fresh) return null;
    if (fresh && fresh.replace === true) base = null;
    var baked = (base && base.reviews) || [];
    /* Genuine-only mode drops the shared showcase reviews and keeps what belongs to this product.
       Moderated submissions from the overlay are genuine by definition. */
    if (GENUINE_ONLY) {
      baked = baked.filter(function (r) {
        return r.own === true;
      });
    }
    var all = baked.concat((fresh && fresh.reviews) || []);
    var seen = {};
    all = all.filter(function (r) {
      var key = (r.author || '') + '|' + (r.date || '') + '|' + (r.text || '').slice(0, 60);
      if (seen[key]) return false;
      seen[key] = true;
      return true;
    });
    all.sort(function (a, b) {
      return toTime(b.date) - toTime(a.date);
    });
    if (!all.length) return null;
    return {
      product_id: (fresh && fresh.product_id) || (base && base.product_id),
      title: (base && base.title) || (fresh && fresh.title) || '',
      reviews: all,
      count: all.length,
      avg: Math.round((sumRatings(all) / all.length) * 10) / 10
    };
  }

  function loadProduct(handle, explicitUrl) {
    if (!handle) return Promise.resolve(null);
    if (productPromises[handle]) return productPromises[handle];

    var inline = readInline('aao-reviews-data-' + handle);
    var basePromise;

    if (inline) {
      basePromise = Promise.resolve(inline);
    } else {
      /* Only fetch a review-list asset when the summary says this handle displays one, and skip
         it entirely in genuine-only mode for a product whose set is shared showcase reviews. */
      basePromise = loadBakedSummary().then(function (summary) {
        var row = summary && summary.products && summary.products[handle];
        if (!row) return null;
        if (GENUINE_ONLY && row.pool) return null;
        return fetchJSON(reviewsAssetUrl(row, explicitUrl));
      });
    }

    productPromises[handle] = Promise.all([basePromise, loadOverlay()]).then(function (res) {
      return mergeProduct(res[0], overlayEntry(res[1], handle));
    });
    return productPromises[handle];
  }

