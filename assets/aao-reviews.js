/* ---------------------------------------------------------------------------------------------
   AAO NATIVE REVIEWS - widget engine
   ---------------------------------------------------------------------------------------------
   Replaces the Loox reviews app. No dependencies, no framework.

   Data source: the baked review assets, split as described in the data section below and
   generated by docs/reviews/split_reviews.py. Read from an inline <script type="application/json">
   when a snippet inlined it, otherwise fetched.
   Review photos are baked as theme asset filenames, not Loox CDN URLs; photoUrl() resolves them
   against the theme's asset directory. Nothing here depends on images.loox.io.

   There is no backend. New reviews are submitted through Shopify's own contact form, which is
   server-rendered by snippets/aao-reviews-widget.liquid; approved ones are added to the baked
   assets by docs/reviews/split_reviews.py and deployed. See docs/reviews/README.md.

   New submissions POST to <endpoint>/submit as
     {handle, rating, author, email, text}
   and expect {"ok": true}.
   --------------------------------------------------------------------------------------------- */

