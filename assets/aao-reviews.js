/* ---------------------------------------------------------------------------------------------
   AAO NATIVE REVIEWS - widget engine
   ---------------------------------------------------------------------------------------------
   Replaces the Loox reviews app. No dependencies, no framework.

   Data sources, merged in this order (later wins per product handle):
     1. The baked Loox migration, split across theme assets (see the data section below) and
        generated by docs/reviews/split_reviews.py. Read from an inline
        <script type="application/json"> when a snippet inlined it, otherwise fetched.
     2. <approval endpoint>/approved.json - reviews approved since the migration, served by the
        agency VPS. Fetched client-side; failure is silent and the baked data still shows.

   Review photos are baked as theme asset filenames, not Loox CDN URLs; photoUrl() resolves them
   against the theme's asset directory. Nothing here depends on images.loox.io.

   New submissions POST to <endpoint>/submit as
     {handle, rating, author, email, text}
   and expect {"ok": true}.
   --------------------------------------------------------------------------------------------- */

